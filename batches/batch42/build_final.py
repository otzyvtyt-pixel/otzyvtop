VALID_CATS = {'shops','finance','delivery','food','beauty','auto','realestate','education','it','travel'}

def main():
    all_c = json.load(open('/home/hatch/workspace/otzyvtop/batch42/all_candidates.json'))
    by_name = {c['name']: c for c in all_c}
    missing = [n for n in SEL if n not in by_name]
    if missing:
        print('MISSING FROM all_candidates.json:', missing); sys.exit(1)
    out = []
    for name, ov in SEL.items():
        c = dict(by_name[name])
        final = {
            'name': ov.get('name', c['name']),
            'category': c['category'],
            'city': CITY.get(c.get('city',''), c.get('city','')),
            'website': c.get('website','') or '',
            'phone': c.get('phone','') or '',
            'email': c.get('email','') or '',
            'description': DESC_RU.get(name, c.get('description','')),
            'statusNote': NOTE_RU.get(name, c.get('statusNote','') or ''),
            'socials': c.get('socials', []) or [],
            'logoUrl': c.get('logoUrl','') or '',
            'status': c.get('status','active') or 'active',
        }
        assert final['category'] in VALID_CATS, (final['name'], final['category'])
        assert 2 <= len(final['name']) <= 120, final['name']
        assert len(final['description']) <= 600, (final['name'], len(final['description']))
        assert len(final['statusNote']) <= 400, (final['name'], len(final['statusNote']))
        assert len(final['city']) <= 80, final['name']
        out.append(final)
    json.dump(out, open('/home/hatch/workspace/otzyvtop/batch42/final-to-add.json','w'), ensure_ascii=False, indent=2)
    print('wrote', len(out), 'entries')
    from collections import Counter
    print(Counter(e['category'] for e in out))
    # sanity: no Ukrainian-only words left in descriptions? spot list of suspicious tokens
    susp = ['прибирання','прибран','ковдр','підтрим','виїзн','хіміч','офіс — вул','пн–пт']
    for e in out:
        for s in ['прибирання','прибранних','прибранных','ковдр','виїзн','підтрим']:
            if s in e['description']:
                print('SUSPICIOUS:', e['name'], s)

if __name__ == '__main__':
    main()
