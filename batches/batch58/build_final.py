STANDALONE = [
    (r"\bі\b", "и"), (r"\bІ\b", "И"), (r"\bта\b", "и"), (r"\bТа\b", "И"),
    (r"\bє\b", "есть"), (r"\bЄ\b", "Есть"), (r"\bз\b", "с"), (r"\bЗ\b", "С"),
    (r"\bзі\b", "со"), (r"\bЗі\b", "Со"), (r"\bу\b", "в"), (r"\bУ\b", "В"),
    (r"\bй\b", "и"), (r"\bЙ\b", "И"),
]

def translate(text):
    # сначала многословные/точные формы по убыванию длины ключа
    for uk, ru in sorted(WORDMAP.items(), key=lambda kv: -len(kv[0])):
        text = re.sub(r"(?<![А-Яа-яЁёЇїЄєҐґІі])" + re.escape(uk) + r"(?![А-Яа-яЁёЇїЄєҐґІі])", ru, text)
    for pat, rep in STANDALONE:
        text = re.sub(pat, rep, text)
    return text

def fix_name(name):
    name = name.replace("Стомато\ufffd\ufffdогія", "Стоматологія")
    name = name.replace("Н\ufffd\ufffdколаевна", "Николаевна")
    name = name.replace("\ufffd", "")
    return name

