def sub_words(text, mapping):
    for uk, ru in sorted(mapping.items(), key=lambda kv: -len(kv[0])):
        text = re.sub(r"(?<![А-Яа-яЁёЇїЄєҐґІі])" + re.escape(uk) + r"(?![А-Яа-яЁёЇїЄєҐґІі])", ru, text)
    return text

