export function extractTopicUa(company: Company): string {
  const hay = `${company.name} ${company.description}`;
  for (const [re, label] of UA_TOPIC_MATCHERS) {
    if (re.test(hay)) return label;
  }
  const fallback: Record<CategoryId, string> = {
    beauty: 'послуги майстрів',
    shops: 'замовлення товарів',
    finance: 'консультацію',
    auto: 'ремонт авто',
    travel: 'оформлення туру',
    education: 'навчання',
    realestate: 'роботи по об’єкту',
    it: 'проєктні завдання',
    delivery: 'доставку посилки',
    food: 'кухню та доставку',
    scammers: 'пропоновані послуги',
  };
  return fallback[company.category];
}

export function detectScamSubtype(company: Company): ScamSubtype {
  const hay = `${company.name} ${company.description}`;
  if (/інтернет-магазин|интернет-магазин|онлайн-магазин|шахрайський магазин|фейковый магазин|побутов\w*\s+технік|бытов\w*\s+техник|смартфон|ноутбук|електронік|электроник|гаджет/i.test(hay)) {
    return 'shop';
  }
  if (/брокер|крипт|трейд|форекс|forex|інвест|инвест|scam-про[еє]кт|нкцпфр|фінансов|финансов|бірж|бирж/i.test(hay)) {
    return 'invest';
  }
  if (/робот|работ|працевлаштув|трудоустройств|віз|виз|паспорт|громадян|граждан|імміграц|иммиграц|польщ|чехі/i.test(hay)) {
    return 'work';
  }
  return 'general';
}

export function buildUaCityRef(city: string): string {
  if (!city) return '';
  return ` (${localizeCity(city, 'ua')})`;
}

