export function extractTopicUa(company: Company): string {
  const hay = `${company.name} ${company.description}`;
  for (const [re, label] of UA_TOPIC_MATCHERS) {
    if (re.test(hay)) return label;
  }
  const fallback: Record<CategoryId, string> = {
    beauty: 'запис та послуги спеціалістів',
    shops: 'замовлення товарів у магазині',
    finance: 'консультацію та оформлення документів',
    auto: 'обслуговування та консультацію щодо авто',
    travel: 'підбір маршруту та оформлення поїздки',
    education: 'навчальний курс і практику',
    realestate: 'консультацію та роботи на об’єкті',
    it: 'технічне завдання та підтримку',
    delivery: 'відправлення та доставку посилки',
    food: 'замовлення та сервіс закладу',
    scammers: 'пропоновані послуги',
  };
  return fallback[company.category];
}

export function buildUaCityRef(city: string): string {
  if (!city) return '';
  return ` (${localizeCity(city, 'ua')})`;
}

