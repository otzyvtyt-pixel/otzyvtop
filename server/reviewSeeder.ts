function getUaReviewRatio(city: string, domain = ''): number {
  const lower = (city || '').trim().toLowerCase();
  if (WEST_CENTER_UA_CITIES.has(lower)) return 0.65;
  if (CENTRAL_NORTH_UA_CITIES.has(lower)) return 0.54;
  if (SOUTH_EAST_UA_CITIES.has(lower)) return 0.4;
  if (NON_UA_LOCATIONS.has(lower) || /\.(ru|by|kz|su)$/i.test(domain)) return 0.15;
  return 0.48;
}

