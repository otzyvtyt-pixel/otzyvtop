function hashString(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function createRng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffled<T>(items: readonly T[], rng: () => number): T[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

function computePopularityScore(company: Company, rngVal: number): number {
  let score = 0;
  if (company.website) score += 0.22;
  if (company.phone) score += 0.16;
  if (company.email) score += 0.11;
  if (company.socials && company.socials.length > 0) score += 0.14;

  const cityLower = company.city.toLowerCase();
  if (MAJOR_CITIES.has(cityLower)) score += 0.16;
  else if (cityLower) score += 0.08;

  if (company.description.length > 260) score += 0.1;
  else if (company.description.length > 140) score += 0.05;

  if (company.status !== 'closed') score += 0.06;

  score += (rngVal - 0.5) * 0.28;
  return Math.max(0, Math.min(1, score));
}

