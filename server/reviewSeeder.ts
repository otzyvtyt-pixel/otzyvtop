function extractTopic(company: Company): string {
  const hay = `${company.name} ${company.description}`;
  for (const [re, label] of TOPIC_MATCHERS) {
    if (re.test(hay)) return label;
  }
  const fallbackByCategory: Record<CategoryId, string> = {
    beauty: 'запись и услуги специалистов',
    shops: 'заказ товаров в магазине',
    finance: 'консультацию и оформление документов',
    auto: 'обслуживание и консультацию по авто',
    travel: 'подбор маршрута и оформление поездки',
    education: 'учебный курс и практику',
    realestate: 'консультацию и работы по объекту',
    it: 'техническую задачу и поддержку',
    delivery: 'отправку и доставку посылки',
    food: 'заказ и сервис заведения',
    scammers: 'предлагаемые услуги',
  };
  return fallbackByCategory[company.category];
}

