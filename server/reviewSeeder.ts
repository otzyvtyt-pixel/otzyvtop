function hashString(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function createRng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffled<T>(items: readonly T[], rng: () => number): T[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

function computePopularityScore(company: Company, rngVal: number): number {
  let score = 0;
  if (company.website) score += 0.22;
  if (company.phone) score += 0.16;
  if (company.email) score += 0.11;
  if (company.socials && company.socials.length > 0) score += 0.14;

  const cityLower = company.city.toLowerCase();
  if (MAJOR_CITIES.has(cityLower)) score += 0.16;
  else if (cityLower) score += 0.08;

  if (company.description.length > 260) score += 0.1;
  else if (company.description.length > 140) score += 0.05;

  if (company.status !== 'closed') score += 0.06;

  score += (rngVal - 0.5) * 0.28;
  return Math.max(0, Math.min(1, score));
}

export function generateSeededReviews(company: Company): Review[] {
  const seed = hashString(`${company.id}|${company.name}|${company.category}`);
  const rng = createRng(seed);

  const popularity = computePopularityScore(company, rng());
  const count = 10 + Math.round(popularity * 10); // Strictly 10..20

  const isScammer = company.category === 'scammers';
  const isClosed = company.status === 'closed';
  const isDefunctScammer = isScammer && company.scamActive === false;
  const uaShare = getUaReviewRatio(company.city, company.domain);

  const ctxRu: Ctx = {
    name: company.name,
    cityRef: company.city ? ` (${company.city})` : '',
    siteRef: company.domain || '',
    topic: extractTopic(company),
  };

  const ctxUa: UaCtx = {
    name: company.name,
    cityRef: buildUaCityRef(company.city),
    siteRef: company.domain || '',
    topic: extractTopicUa(company),
  };

  const qualityBias = isScammer
    ? 0.05
    : isClosed
      ? 0.42
      : 0.66 + popularity * 0.26;

  // Unique chronologically spread dates.
  // Scammers use their verified [activityPeriodStart, activityPeriodEnd] window so defunct/dead scams never show 2026 reviews.
  let baseEndMs = ANCHOR_MS;
  const dayOffsets: number[] = [];
  const usedDays = new Set<number>();

  if (isScammer && company.activityPeriodEnd) {
    const parsedEnd = Date.parse(`${company.activityPeriodEnd}T18:00:00Z`);
    const parsedStart = company.activityPeriodStart
      ? Date.parse(`${company.activityPeriodStart}T09:00:00Z`)
      : parsedEnd - 365 * DAY_MS;
    if (Number.isFinite(parsedEnd)) {
      baseEndMs = Math.min(ANCHOR_MS, parsedEnd);
      const spanDays = Math.max(
        count + 14,
        Math.floor((baseEndMs - (Number.isFinite(parsedStart) ? parsedStart : baseEndMs - 365 * DAY_MS)) / DAY_MS),
      );
      for (let i = 0; i < count; i++) {
        let dayOffset = Math.floor(Math.pow(rng(), 1.1) * spanDays);
        while (usedDays.has(dayOffset)) {
          dayOffset += 1;
        }
        if (dayOffset > spanDays) {
          dayOffset = spanDays;
          while (usedDays.has(dayOffset) && dayOffset > 0) dayOffset -= 1;
        }
        usedDays.add(dayOffset);
        dayOffsets.push(dayOffset);
      }
      dayOffsets.sort((a, b) => a - b);
    }
  }

  if (dayOffsets.length === 0) {
    for (let i = 0; i < count; i++) {
      let dayOffset: number;
      if (isClosed && !isScammer && i === 0) {
        dayOffset = Math.floor(rng() * 28) + 2;
      } else if (isClosed && !isScammer) {
        dayOffset = 110 + Math.floor(Math.pow(rng(), 1.15) * 710);
      } else {
        dayOffset = Math.floor(Math.pow(rng(), 1.35) * 650) + 1;
      }
      while (usedDays.has(dayOffset)) {
        dayOffset += 1;
      }
      usedDays.add(dayOffset);
      dayOffsets.push(dayOffset);
    }
    dayOffsets.sort((a, b) => a - b);
  }

  // Shuffle RU & UA pools independently without replacement so ZERO phrases repeat
  const authorsRu = shuffled(REVIEWER_NAMES, rng);
  const openersRu = shuffled(CATEGORY_OPENERS[company.category] || CATEGORY_OPENERS.shops, rng);
  const posMidRu = shuffled(POS_MIDDLES, rng);
  const posEndRu = shuffled(POS_ENDINGS, rng);
  const neuMidRu = shuffled(NEU_MIDDLES, rng);
  const neuEndRu = shuffled(NEU_ENDINGS, rng);
  const negMidRu = shuffled(NEG_MIDDLES, rng);
  const negEndRu = shuffled(NEG_ENDINGS, rng);
  const scamMidRu = shuffled(SCAM_MIDDLES, rng);
  const scamEndRu = shuffled(isDefunctScammer ? SCAM_ARCHIVE_ENDINGS : SCAM_ENDINGS, rng);
  const prosRu = shuffled(PROS_BY_CATEGORY[company.category] || PROS_BY_CATEGORY.shops, rng);
  const consRu = shuffled(CONS_BY_CATEGORY[company.category] || CONS_BY_CATEGORY.shops, rng);

  const authorsUa = shuffled(UA_REVIEWER_NAMES, rng);
  const openersUa = shuffled(UA_CATEGORY_OPENERS[company.category] || UA_CATEGORY_OPENERS.shops, rng);
  const posMidUa = shuffled(UA_POS_MIDDLES, rng);
  const posEndUa = shuffled(UA_POS_ENDINGS, rng);
  const neuMidUa = shuffled(UA_NEU_MIDDLES, rng);
  const neuEndUa = shuffled(UA_NEU_ENDINGS, rng);
  const negMidUa = shuffled(UA_NEG_MIDDLES, rng);
  const negEndUa = shuffled(UA_NEG_ENDINGS, rng);
  const scamMidUa = shuffled(UA_SCAM_MIDDLES, rng);
  const scamEndUa = shuffled(isDefunctScammer ? UA_SCAM_ARCHIVE_ENDINGS : UA_SCAM_ENDINGS, rng);
  const prosUa = shuffled(UA_PROS_BY_CATEGORY[company.category] || UA_PROS_BY_CATEGORY.shops, rng);
  const consUa = shuffled(UA_CONS_BY_CATEGORY[company.category] || UA_CONS_BY_CATEGORY.shops, rng);

  let ruOpIdx = 0, ruPosIdx = 0, ruNeuIdx = 0, ruNegIdx = 0, ruScamIdx = 0, ruProIdx = 0, ruConIdx = 0;
  let uaOpIdx = 0, uaPosIdx = 0, uaNeuIdx = 0, uaNegIdx = 0, uaScamIdx = 0, uaProIdx = 0, uaConIdx = 0;

  const reviews: Review[] = [];

  for (let i = 0; i < count; i++) {
    const isUa = rng() < uaShare;
    const author = isUa
      ? authorsUa[i % authorsUa.length]
      : authorsRu[i % authorsRu.length];

    let rating: number;
    const roll = rng();
    if (isScammer) {
      if (roll < 0.72) rating = 1;
      else if (roll < 0.94) rating = 2;
      else rating = 3;
    } else if (isClosed && i === 0) {
      rating = rng() < 0.6 ? 2 : 1;
    } else if (isClosed) {
      if (roll < 0.25) rating = 1;
      else if (roll < 0.5) rating = 2;
      else if (roll < 0.76) rating = 3;
      else if (roll < 0.92) rating = 4;
      else rating = 5;
    } else {
      if (roll < qualityBias * 0.72) rating = 5;
      else if (roll < qualityBias * 0.96) rating = 4;
      else if (roll < 0.92) rating = 3;
      else if (roll < 0.97) rating = 2;
      else rating = 1;
    }

    let text = '';
    if (isClosed && !isScammer && i === 0) {
      const noteIdx = Math.floor(rng() * 2);
      text = isUa
        ? UA_CLOSED_NOTES[noteIdx](company.name, company.domain)
        : RU_CLOSED_NOTES[noteIdx](company.name, company.domain);
    } else if (isUa) {
      const opener = openersUa[uaOpIdx++ % openersUa.length](ctxUa);
      let middle = '';
      let ending = '';
      if (isScammer) {
        middle = scamMidUa[uaScamIdx % scamMidUa.length];
        ending = scamEndUa[(uaScamIdx + 3) % scamEndUa.length];
        uaScamIdx++;
      } else if (rating >= 4) {
        middle = posMidUa[uaPosIdx % posMidUa.length];
        ending = posEndUa[(uaPosIdx + 5) % posEndUa.length];
        uaPosIdx++;
      } else if (rating === 3) {
        middle = neuMidUa[uaNeuIdx % neuMidUa.length];
        ending = neuEndUa[(uaNeuIdx + 4) % neuEndUa.length];
        uaNeuIdx++;
      } else {
        middle = negMidUa[uaNegIdx % negMidUa.length];
        ending = negEndUa[(uaNegIdx + 2) % negEndUa.length];
        uaNegIdx++;
      }
      text = rng() < 0.22 ? `${opener} ${middle}` : `${opener} ${middle} ${ending}`;
    } else {
      const opener = openersRu[ruOpIdx++ % openersRu.length](ctxRu);
      let middle = '';
      let ending = '';
      if (isScammer) {
        middle = scamMidRu[ruScamIdx % scamMidRu.length];
        ending = scamEndRu[(ruScamIdx + 3) % scamEndRu.length];
        ruScamIdx++;
      } else if (rating >= 4) {
        middle = posMidRu[ruPosIdx % posMidRu.length];
        ending = posEndRu[(ruPosIdx + 5) % posEndRu.length];
        ruPosIdx++;
      } else if (rating === 3) {
        middle = neuMidRu[ruNeuIdx % neuMidRu.length];
        ending = neuEndRu[(ruNeuIdx + 4) % neuEndRu.length];
        ruNeuIdx++;
      } else {
        middle = negMidRu[ruNegIdx % negMidRu.length];
        ending = negEndRu[(ruNegIdx + 2) % negEndRu.length];
        ruNegIdx++;
      }
      text = rng() < 0.22 ? `${opener} ${middle}` : `${opener} ${middle} ${ending}`;
    }

    const pros =
      !isScammer && !(isClosed && i === 0) && rating >= 3 && rng() < 0.76
        ? isUa
          ? prosUa[uaProIdx++ % prosUa.length]
          : prosRu[ruProIdx++ % prosRu.length]
        : '';
    const cons =
      isScammer || (rating <= 3 ? rng() < 0.85 : rng() < 0.42)
        ? isUa
          ? consUa[uaConIdx++ % consUa.length]
          : consRu[ruConIdx++ % consRu.length]
        : '';

    const hourOffsetMs =
      Math.floor(rng() * 14) * 3_600_000 + Math.floor(rng() * 59) * 60_000;
    const createdMs = baseEndMs - dayOffsets[i] * DAY_MS - hourOffsetMs;
    const createdAt = new Date(createdMs).toISOString();

    const helpfulCount = isScammer
      ? Math.floor(rng() * 19) + 2
      : i < 4
        ? Math.floor(rng() * 14) + 1
        : Math.floor(rng() * 6);
    const unhelpfulCount = rng() < 0.25 ? Math.floor(rng() * 3) : 0;

    const comments: ReviewComment[] = [];
    if (!isScammer && !isClosed && i < 3 && rng() < 0.45) {
      const replyCreatedAt = new Date(
        Math.min(ANCHOR_MS, createdMs + (1 + Math.floor(rng() * 3)) * DAY_MS),
      ).toISOString();
      const replyIdx = rating >= 4 ? (rng() < 0.5 ? 0 : 1) : 2;
      comments.push({
        id: `cmt_seed_${company.id}_${i}`,
        author: isUa ? `Представник ${company.name}` : `Представитель ${company.name}`,
        text: isUa
          ? UA_OFFICIAL_REPLIES[replyIdx](company.name)
          : OFFICIAL_REPLIES[replyIdx](company.name),
        isOfficialReply: true,
        createdAt: replyCreatedAt,
      });
    }

    reviews.push({
      id: `seed_${company.id}_${i}`,
      companyId: company.id,
      author,
      rating,
      pros,
      cons,
      text,
      confirmedPurchase: !isScammer && !(isClosed && i === 0) && rng() < 0.68,
      createdAt,
      helpfulCount,
      unhelpfulCount,
      comments,
    });
  }

  reviews.sort((a, b) => b.createdAt.localeCompare(a.createdAt));
  return reviews;
}

export function computeSeededSummary(company: Company): {
  reviewCount: number;
  averageRating: number;
} {
  const reviews = generateSeededReviews(company);
  const sum = reviews.reduce((acc, r) => acc + r.rating, 0);
  return {
    reviewCount: reviews.length,
    averageRating: Math.round((sum / reviews.length) * 10) / 10,
  };
}
