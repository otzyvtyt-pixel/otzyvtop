const CITY_SLUG_TO_CANONICAL: Map<string, string> = (() => {
  const map = new Map<string, string>();
  for (const [ruLower, uaName] of Object.entries(CITY_RU_TO_UA)) {
    const ruTitle = ruLower
      .split(/([\s-])/)
      .map((part) => (part === ' ' || part === '-' ? part : part.charAt(0).toUpperCase() + part.slice(1)))
      .join('');
    map.set(citySlug(ruLower), ruTitle);
    map.set(citySlug(uaName), ruTitle);
  }
  // Common English/international transliteration aliases for Ukrainian cities
  map.set('kyiv', 'Киев');
  map.set('kiev', 'Киев');
  map.set('lviv', 'Львов');
  map.set('odesa', 'Одесса');
  map.set('odessa', 'Одесса');
  map.set('dnipro', 'Днепр');
  map.set('kharkiv', 'Харьков');
  map.set('zaporizhzhia', 'Запорожье');
  map.set('vinnytsia', 'Винница');
  map.set('ivano-frankivsk', 'Ивано-Франковск');
  map.set('mykolaiv', 'Николаев');
  map.set('chernivtsi', 'Черновцы');
  map.set('ternopil', 'Тернополь');
  map.set('rivne', 'Ровно');
  map.set('uzhhorod', 'Ужгород');
  map.set('chernihiv', 'Чернигов');
  map.set('zhytomyr', 'Житомир');
  map.set('khmelnytskyi', 'Хмельницкий');
  map.set('kropyvnytskyi', 'Кропивницкий');
  map.set('cherkasy', 'Черкассы');
  map.set('poltava', 'Полтава');
  map.set('lutsk', 'Луцк');
  map.set('sumy', 'Сумы');
  return map;
})();

export function localizeCity(city: string, lang: Language): string {
  const clean = (city || '').trim();
  if (!clean) return '';
  if (lang === 'ru') return clean;
  return CITY_RU_TO_UA[clean.toLowerCase()] || clean;
}

export function resolveCanonicalCityQuery(queryOrSlug: string): string {
  const clean = (queryOrSlug || '').trim();
  if (!clean) return '';
  const slug = citySlug(clean);
  return CITY_SLUG_TO_CANONICAL.get(slug) || clean;
}
